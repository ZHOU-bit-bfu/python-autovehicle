# ============================================================================
# 练习 1: 列表基础
# ============================================================================
speed = [0, 20, 45, 60, 80]
print(len(speed))       # 列表长度
print(speed[0])         # 第一个值（索引从 0 开始！）
print(speed[-1])        # 最后一个值

# ============================================================================
# 练习 2: for 循环遍历
# ============================================================================
for s in speed:
    v = s / 3.6
    print(f"{s} km/h = {v:.1f} m/s")

# ============================================================================
# 练习 3: enumerate
# ============================================================================
distances = [25.0, 4.5, 18.2, 6.8, 2.3]
for i, d in enumerate(distances):
    print(f"障碍物 {i+1}: 距离 {d:.1f} m")

# ============================================================================
# 练习 4: 列表推导式
# ============================================================================
distances = [25.0, 4.5, 18.2, 6.8, 2.3]
danger = [d for d in distances if d < 10]
print(f"危险障碍物: {danger}")

# ============================================================================
# 练习 5: 综合 — TTC 批量计算
# ============================================================================
ego_v = 30
targets = [(20.0, 25.0), (8.0, 5.0), (35.0, 28.0), (3.0, 2.0)]

for i, t in enumerate(targets):
    dist, obj_v = t
    rel_v = ego_v - obj_v
    if rel_v > 0:
        ttc = dist / rel_v
        print(f"目标{i+1}: TTC = {ttc:.1f}s")
    else:
        print(f"目标{i+1}: 不会碰撞")
