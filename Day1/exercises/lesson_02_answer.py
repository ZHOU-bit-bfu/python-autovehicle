# ============================================================================
# 练习 1: 速度单位换算
# ============================================================================
speed = 120
speed_ms = speed / 3.6
print(f"转换后的车速为{speed_ms:.2f}m/s")

# ============================================================================
# 练习 2: 电机功率计算
# ============================================================================
torque = 350
rpm = 4500
p = torque * rpm * 3.14159 / 30
p_kw = p / 1000
print(f"电机输出功率为{p_kw:.1f}kW")

# ============================================================================
# 练习 3: 电池续航估算
# ============================================================================
capacity = 86
consumption = 16.5
range_km = capacity / consumption * 100
print(f"理论续航{range_km:.0f}km")

# ============================================================================
# 练习 4: 字符串处理
# ============================================================================
vin = "  lfv3a28k5d3000001  "
vin = vin.strip().upper()
print(f"修改后的字符串: {vin}")

# ============================================================================
# 练习 5: 制动距离估算
# ============================================================================
v = 100                    # km/h
mu = 0.8
g = 9.81
v_ms = v / 3.6             # 先转 m/s！
d = v_ms ** 2 / (2 * mu * g)
print(f"制动距离{d:.1f}m")
