# ============================================================================
# 练习 1: 车速判断
# ============================================================================
speed = 95

if speed > 120:
    print("严重超速")
elif speed > 80:
    print("超速")
elif speed > 60:
    print("正常")
else:
    print("低速")

# ============================================================================
# 练习 2: SOC 电量判断
# ============================================================================
soc = 25

if soc < 10:
    print("电量不足，请立即充电")
elif soc < 30:
    print("电量偏低")
elif soc < 80:
    print("电量正常")
else:
    print("电量充足")

# ============================================================================
# 练习 3: 制动温度告警
# ============================================================================
temp = 320
wear = 0.6

if temp > 500 or wear > 0.8:
    print("制动系统过热/磨损，立即停车")
elif temp > 300 or wear > 0.5:
    print("制动系统注意检查")
else:
    print("制动系统正常")

