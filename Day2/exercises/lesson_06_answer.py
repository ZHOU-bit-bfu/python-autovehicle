# 练习 3: 多返回值函数
# ============================================================================
def speed_summary(speeds):
    """返回(最低速, 最高速, 平均速度)"""
    return min(speeds), max(speeds), sum(speeds) / len(speeds)


test_data = [45, 62, 88, 73, 95, 51]
v_min, v_max, v_avg = speed_summary(test_data)
print(f"最低: {v_min}, 最高: {v_max}, 平均: {v_avg:.1f}")

