# 练习 1: km/h → m/s 函数
# ============================================================================
def kmh_to_ms(speed):
    """将 km/h 转换为 m/s"""
    return speed / 3.6


print(f"60 km/h = {kmh_to_ms(60):.1f} m/s")
print(f"80 km/h = {kmh_to_ms(80):.1f} m/s")
print(f"120 km/h = {kmh_to_ms(120):.1f} m/s")

