# 练习 2: TTC 计算函数
# ============================================================================
def calculate_ttc(distance, ego_v, obj_v):
    """计算碰撞时间，不会碰撞返回 -1"""
    rel_v = ego_v - obj_v
    if rel_v <= 0:
        return -1
    return distance / rel_v


print(f"TTC(50, 25, 10) = {calculate_ttc(50, 25, 10):.1f}s")   # 3.3s
print(f"TTC(30, 20, 25) = {calculate_ttc(30, 20, 25)}")        # -1

