# 练习 4: 带默认参数的制动距离
# ============================================================================
def calc_brake_dist(speed_kmh, mu=0.8):
    """计算制动距离"""
    v_ms = speed_kmh / 3.6
    return v_ms ** 2 / (2 * mu * 9.81)


print(f"干路面 100km/h: {calc_brake_dist(100, mu=0.8):.1f}m")
print(f"湿路面 100km/h: {calc_brake_dist(100, mu=0.4):.1f}m")

