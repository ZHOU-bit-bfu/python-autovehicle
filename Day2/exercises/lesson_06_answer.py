# 练习 5: 电池续航判断
# ============================================================================
def battery_advice(soc, distance_to_station):
    """根据 SOC 和距离返回建议"""
    if soc < 10:
        return "电量极低，立即靠边！"
    range_km = soc * 4   # 每1%跑4km
    if range_km < distance_to_station:
        return "可能无法到达充电站，请节省电量"
    else:
        return "可安全到达充电站"


print(f"(25, 80): {battery_advice(25, 80)}")
print(f"(8, 50): {battery_advice(8, 50)}")
print(f"(60, 100): {battery_advice(60, 100)}")
